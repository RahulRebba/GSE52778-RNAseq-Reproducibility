-- ============================================================
-- GSE52778 Gene Expression Project
-- Oracle-Compatible Relational Schema
--
-- Portfolio representation of the final SQLite data model.
-- ============================================================


-- ------------------------------------------------------------
-- 1. STUDY
-- One row per public gene-expression study
-- ------------------------------------------------------------

CREATE TABLE STUDY (
    STUDY_ID VARCHAR2(30) PRIMARY KEY,
    TITLE VARCHAR2(500) NOT NULL,
    ORGANISM VARCHAR2(100),
    PLATFORM VARCHAR2(200),
    SOURCE_URL VARCHAR2(1000)
);


-- ------------------------------------------------------------
-- 2. SAMPLE
-- One row per biological RNA-seq sample
-- ------------------------------------------------------------

CREATE TABLE SAMPLE (
    SAMPLE_ID VARCHAR2(30) PRIMARY KEY,
    STUDY_ID VARCHAR2(30) NOT NULL,
    GEO_SAMPLE VARCHAR2(30) NOT NULL UNIQUE,
    DONOR VARCHAR2(50) NOT NULL,
    TREATMENT VARCHAR2(100) NOT NULL,
    DEX VARCHAR2(30) NOT NULL,
    INCLUDE_PRIMARY_ANALYSIS NUMBER(1) NOT NULL,

    CONSTRAINT CK_SAMPLE_PRIMARY
        CHECK (INCLUDE_PRIMARY_ANALYSIS IN (0, 1)),

    CONSTRAINT FK_SAMPLE_STUDY
        FOREIGN KEY (STUDY_ID)
        REFERENCES STUDY(STUDY_ID)
        ON DELETE CASCADE
);


-- ------------------------------------------------------------
-- 3. SAMPLE QC
-- Sample-level QC and normalisation information
-- ------------------------------------------------------------

CREATE TABLE SAMPLE_QC (
    SAMPLE_ID VARCHAR2(30) PRIMARY KEY,
    METADATA_STATUS VARCHAR2(30) NOT NULL,
    RAW_LIBRARY_MILLIONS NUMBER,
    SIZE_FACTOR NUMBER,
    PC1 NUMBER,
    PC2 NUMBER,
    OUTLIER_FLAG VARCHAR2(30),
    NOTE VARCHAR2(1000),

    CONSTRAINT FK_SAMPLE_QC_SAMPLE
        FOREIGN KEY (SAMPLE_ID)
        REFERENCES SAMPLE(SAMPLE_ID)
        ON DELETE CASCADE
);


-- ------------------------------------------------------------
-- 4. GENE
-- Gene annotation stored once
-- ------------------------------------------------------------

CREATE TABLE GENE (
    ENSEMBL_GENE_ID VARCHAR2(40) PRIMARY KEY,
    GENE_SYMBOL VARCHAR2(100),
    GENE_NAME VARCHAR2(1000),
    GENE_BIOTYPE VARCHAR2(100)
);


-- ------------------------------------------------------------
-- 5. ANALYSIS RUN
-- Statistical model / analysis provenance
-- ------------------------------------------------------------

CREATE TABLE ANALYSIS_RUN (
    ANALYSIS_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    STUDY_ID VARCHAR2(30) NOT NULL,
    ANALYSIS_NAME VARCHAR2(300) NOT NULL,
    ANALYSIS_TYPE VARCHAR2(100) NOT NULL,

    IS_PRIMARY NUMBER(1) NOT NULL,

    DESIGN_FORMULA VARCHAR2(200),
    FILTER_RULE VARCHAR2(500),

    ALPHA NUMBER,
    EFFECT_SIZE_THRESHOLD NUMBER,

    RESULT_PROVENANCE VARCHAR2(1000),

    CREATED_AT TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CK_ANALYSIS_PRIMARY
        CHECK (IS_PRIMARY IN (0, 1)),

    CONSTRAINT FK_ANALYSIS_STUDY
        FOREIGN KEY (STUDY_ID)
        REFERENCES STUDY(STUDY_ID)
        ON DELETE CASCADE
);


-- ------------------------------------------------------------
-- 6. ANALYSIS RESULT
-- Gene-level differential-expression statistics
-- ------------------------------------------------------------

CREATE TABLE ANALYSIS_RESULT (
    ANALYSIS_ID NUMBER NOT NULL,
    ENSEMBL_GENE_ID VARCHAR2(40) NOT NULL,

    BASEMEAN NUMBER,
    LOG2FOLDCHANGE NUMBER,
    LFCSE NUMBER,
    STAT NUMBER,
    PVALUE NUMBER,
    PADJ NUMBER,

    RESULT_CLASS VARCHAR2(100),

    CONSTRAINT PK_ANALYSIS_RESULT
        PRIMARY KEY (
            ANALYSIS_ID,
            ENSEMBL_GENE_ID
        ),

    CONSTRAINT FK_RESULT_ANALYSIS
        FOREIGN KEY (ANALYSIS_ID)
        REFERENCES ANALYSIS_RUN(ANALYSIS_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_RESULT_GENE
        FOREIGN KEY (ENSEMBL_GENE_ID)
        REFERENCES GENE(ENSEMBL_GENE_ID)
        ON DELETE CASCADE
);


-- ------------------------------------------------------------
-- 7. GO ENRICHMENT
-- Simplified GO Biological Process enrichment
-- ------------------------------------------------------------

CREATE TABLE GO_ENRICHMENT (
    ENRICHMENT_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    ANALYSIS_ID NUMBER NOT NULL,

    DIRECTION VARCHAR2(30) NOT NULL,
    ONTOLOGY VARCHAR2(20)
        DEFAULT 'BP'
        NOT NULL,

    GO_ID VARCHAR2(30) NOT NULL,
    DESCRIPTION VARCHAR2(1000) NOT NULL,

    GENE_RATIO VARCHAR2(50),
    BACKGROUND_RATIO VARCHAR2(50),

    PVALUE NUMBER,
    ADJUSTED_P_VALUE NUMBER,
    Q_VALUE NUMBER,

    GENE_COUNT NUMBER,
    GENE_IDS CLOB,

    CONSTRAINT FK_GO_ANALYSIS
        FOREIGN KEY (ANALYSIS_ID)
        REFERENCES ANALYSIS_RUN(ANALYSIS_ID)
        ON DELETE CASCADE,

    CONSTRAINT UQ_GO_RESULT
        UNIQUE (
            ANALYSIS_ID,
            DIRECTION,
            GO_ID
        )
);


-- ------------------------------------------------------------
-- 8. ANALYSIS SUMMARY
-- Headline project metrics for reporting / Power BI
-- ------------------------------------------------------------

CREATE TABLE ANALYSIS_SUMMARY (
    SUMMARY_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    STUDY_ID VARCHAR2(30) NOT NULL,

    METRIC VARCHAR2(300) NOT NULL,

    NUMERIC_VALUE NUMBER,
    TEXT_VALUE VARCHAR2(1000),
    UNIT VARCHAR2(100),

    CONSTRAINT FK_SUMMARY_STUDY
        FOREIGN KEY (STUDY_ID)
        REFERENCES STUDY(STUDY_ID)
        ON DELETE CASCADE,

    CONSTRAINT UQ_SUMMARY_METRIC
        UNIQUE (
            STUDY_ID,
            METRIC
        )
);


-- ============================================================
-- INDEXES
-- Improve common filtering and join operations
-- ============================================================

CREATE INDEX IDX_SAMPLE_STUDY
ON SAMPLE(STUDY_ID);


CREATE INDEX IDX_SAMPLE_DONOR
ON SAMPLE(DONOR);


CREATE INDEX IDX_ANALYSIS_STUDY
ON ANALYSIS_RUN(STUDY_ID);


CREATE INDEX IDX_RESULT_GENE
ON ANALYSIS_RESULT(ENSEMBL_GENE_ID);


CREATE INDEX IDX_RESULT_PADJ
ON ANALYSIS_RESULT(
    ANALYSIS_ID,
    PADJ
);


CREATE INDEX IDX_RESULT_CLASS
ON ANALYSIS_RESULT(
    ANALYSIS_ID,
    RESULT_CLASS
);


CREATE INDEX IDX_GO_DIRECTION
ON GO_ENRICHMENT(
    ANALYSIS_ID,
    DIRECTION,
    ADJUSTED_P_VALUE
);